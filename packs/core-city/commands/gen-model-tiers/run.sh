#!/usr/bin/env bash
#
# gen-model-tiers — expand the core-city base tier map across the CURRENT
# city's project rigs and print a city TOML fragment of [[patches.agent]]
# blocks to stdout. Redirect into an included fragment:
#
#   cd cities/<city> && gc cc gen-model-tiers > model-tiers.toml
#   # then in city.toml:  include = ["model-tiers.toml"]
#
# The role -> tier data lives in core-city/model-tiers.base.toml (edit there).
# Rigs are auto-detected from the running city, so adding a rig + regenerating
# is all it takes to cover it. The city root (HQ) is excluded.

set -euo pipefail

# Locate the base map inside the core-city pack (GC_PACK_DIR is set for pack
# commands; fall back to this script's location: commands/gen-model-tiers/ -> pack root).
pack_dir="${GC_PACK_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
base="$pack_dir/model-tiers.base.toml"

if [ ! -f "$base" ]; then
  echo "gen-model-tiers: base map not found at $base" >&2
  exit 1
fi

# Project rigs in this city (exclude the city root / HQ entry).
city_name="$(gc rig list --json 2>/dev/null | jq -r '.city_name')"
mapfile -t rigs < <(gc rig list --json 2>/dev/null | jq -r --arg c "$city_name" '.rigs[] | select(.name != $c) | .name')

if [ "${#rigs[@]}" -eq 0 ]; then
  echo "gen-model-tiers: no project rigs found in city $city_name" >&2
  exit 0
fi

printf '# GENERATED by "gc cc gen-model-tiers" — do not edit by hand.\n'
printf '# Source: core-city/model-tiers.base.toml. Regenerate after changing\n'
printf '# rigs, roles, or tiers:  gc cc gen-model-tiers > model-tiers.toml\n\n'

# Read "role = \"tier\"" pairs from the base map's [tiers] table (skip comments/headers).
while IFS='=' read -r role tier; do
  role="$(printf '%s' "$role" | tr -d '[:space:]')"
  tier="$(printf '%s' "$tier" | tr -d '[:space:]"')"
  [ -z "$role" ] && continue
  for rig in "${rigs[@]}"; do
    printf '[[patches.agent]]\ndir = "%s"\nname = "%s"\nprovider = "%s"\n\n' "$rig" "$role" "$tier"
  done
done < <(grep -E '^[a-zA-Z][a-zA-Z0-9-]*[[:space:]]*=[[:space:]]*"' "$base")
